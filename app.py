def valid_greek_afm(afm):
    afm = str(afm).strip()

    if len(afm) != 9 or not afm.isascii() or not afm.isdigit():
        return False

    total = sum(
        int(afm[i]) * (2 ** (8 - i))
        for i in range(8)
    )

    check_digit = (total % 11) % 10

    return check_digit == int(afm[8])


